def translate(col_name: str) -> str:
    """Translate an English column name to Spanish.

    Handles the 'X per 90' pattern automatically: translates the base name
    and appends 'por 90'.
    """
    if col_name in _TRANSLATIONS:
        return _TRANSLATIONS[col_name]

    # Pattern: "Something per 90"
    if col_name.endswith(' per 90'):
        base = col_name[:-7]  # strip ' per 90'
        translated_base = _TRANSLATIONS.get(base, base)
        return f'{translated_base} por 90'

    # Fallback: return original
    return col_name
